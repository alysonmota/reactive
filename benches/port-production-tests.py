#!/usr/bin/env python3
"""Reproducible public-contract ports, preserving production test assertions.

Not a claim that tests involving different private storage are inapplicable:
the inventory separately records those cases for manual review.
"""
import hashlib
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'experiments/typed-runtime/src/production_ports.rs'
BLOCK = re.compile(r'\.inner|\bcontext::|\bStorage\b|SlotId|Payload|NodeKind|Signal::new|HandleId|Operation::|enter_evaluation|check_computation|crate::context|RuntimeId')
EXCLUDE = {
    'no_drop_erased_classification_mismatch_retains_destructor_capability_and_poison',
    'retirement_empties_reusable_cell_even_when_slot_allocation_is_retained',
    'handles_reject_kind_and_erased_value_type_mismatches',
    'root_and_node_reuse_rejects_old_handles_and_old_disposal_is_noop',
    'final_facade_release_drops_values_without_callbacks',
    'poison_preserves_first_failure_and_allows_only_diagnostics_and_teardown',
    'clone_cannot_dispose_target_and_working_copy_commits_after_borrow_ends',
    'equal_candidate_drops_once_without_replacing_snapshot',
    'comparator_panic_and_candidate_destructor_panic_preserve_first_panic',
    'rejected_creation_drains_both_value_and_comparator_even_if_both_panic',
    'identity_allocation_is_unique_across_threads_without_sharing_runtimes',
    'pure_capabilities_apply_to_other_runtimes_and_never_poison_local_errors',
}

def tests(text):
    for m in re.finditer(r'#\[test\]\s*fn (\w+)\(\)\s*\{', text):
        # Rust test strings in these sources have balanced braces. Verify the
        # generated result with cargo fmt/check; never silently edit assertions.
        depth, end = 1, m.end()
        while depth:
            depth += (text[end] == '{') - (text[end] == '}')
            end += 1
        yield m.group(1), text[m.start():end]

def adapt(text):
    text = text.replace('crate::RuntimeStatus', 'RuntimeStatus').replace('crate::WeakRuntime', 'WeakRuntime')
    text = text.replace('crate::FlushReport', 'FlushReport').replace('crate::Signal', 'Signal')
    text = text.replace('crate::Memo', 'Memo')
    text = re.sub(r'\.flush\(', '.flush_with(', text)
    text = re.sub(r'\.dispose\(', '.dispose_any(', text)
    text = text.replace('.id.slot', '.key')
    text = text.replace('.id.runtime', '.runtime')
    text = text.replace('report.failure.as_deref()', 'report.failure.as_ref()')
    text = text.replace('Memo::<String>::new(value.id)', 'forge::<_,String>(value)')
    # Hook signature differs; the adapter is explicit and test-only.
    text = text.replace('.set_request_flush_hook(', '.install_hook(')
    return text

def main():
    parser=argparse.ArgumentParser(__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    chunks = ['// Generated by benches/port-production-tests.py. Do not edit.\n#![allow(clippy::clone_on_copy)] // Production errors are Clone, typed errors are also Copy.\nuse super::production_support::*;\n']
    inventory = []
    for path in sorted((ROOT/'src').rglob('*.rs')):
        text = path.read_text()
        selected = []
        for name, body in tests(text):
            port = path.name not in ['arena.rs', 'context.rs', 'graph.rs', 'conformance.rs'] and not BLOCK.search(body) and name not in EXCLUDE
            inventory.append({'source':str(path.relative_to(ROOT)), 'test':name, 'source_sha256':hashlib.sha256(body.encode()).hexdigest(),
                              'port':f'production_ports::{path.stem}::{name}' if port else None})
            if port:
                selected.append(adapt(body))
        if selected:
            helpers = ''
            if path.stem in ['effects','memos','ownership']:
                helpers += 'fn setup()->(Runtime,OwnerHandle){pair()}\n'
            if path.stem == 'signals':
                helpers += 'fn setup<T:PartialEq+\'static>(v:T)->(Runtime,OwnerHandle,Signal<T>){let (r,o)=pair();let s=signal(&r,o,v);(r,o,s)}\n'
            if path.stem == 'scheduling':
                helpers += 'fn setup()->(Runtime,OwnerHandle,Signal<i32>){let(r,o)=pair();let s=signal(&r,o,0);(r,o,s)}\nfn install(rt:&Runtime)->Rc<Cell<usize>>{let n=Rc::new(Cell::new(0));let c=n.clone();rt.install_hook(move |_|c.set(c.get()+1)).unwrap();n}\n'
            cfg = '#[cfg(feature="diagnostics")]\n' if path.stem == 'diagnostics' else ''
            chunks.append(cfg+'mod '+path.stem+' {\nuse super::*;\n'+helpers+'\n'.join(selected)+'\n}\n')
    formatted=subprocess.run(['rustfmt','--edition','2024','--emit','stdout'],input='\n'.join(chunks),text=True,capture_output=True,check=True).stdout
    inventory_text=json.dumps(inventory,indent=2)+'\n'
    inventory_path=ROOT/'benches/.log/production-test-inventory.json'
    if args.check:
        assert OUT.read_text()==formatted,'Regenerate production ports'
        assert inventory_path.read_text()==inventory_text,'Regenerate production inventory'
    else:
        OUT.write_text(formatted);inventory_path.write_text(inventory_text)
    print(f'{sum(x["port"] is not None for x in inventory)} direct ports / {len(inventory)} production tests')

if __name__ == '__main__':
    main()
